export function getTemplate(id?: string): StoryTemplate | undefined {
  if (!id) return undefined;
  return TEMPLATES.find((item) => item.id === id);
}

export function createStory(templateId?: string): StoryDoc {
  const template = getTemplate(templateId) ?? TEMPLATES[TEMPLATES.length - 1];
  return cloneDoc(template.doc);
}
